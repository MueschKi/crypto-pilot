import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const html=fs.readFileSync('puck-pulse/index.html','utf8');
const config=JSON.parse(fs.readFileSync('puck-pulse-worker.jsonc','utf8'));
assert.equal(config.name,'puck-pulse');
assert.equal(config.workers_dev,true);
assert.equal(config.assets.directory,'./puck-pulse');
assert.ok(html.startsWith('<!doctype html>'));
assert.match(html,/<title>PUCK PULSE/);
assert.match(html,/name="viewport"/);
assert.match(html,/id="rink"/);
assert.match(html,/id="modeGroup"/);
assert.match(html,/data-mode="ai"/);
assert.match(html,/data-mode="local"/);
assert.match(html,/id="arenas"/);
assert.match(html,/id="startBtn"/);
assert.match(html,/id="musicToggle"/);
assert.match(html,/id="fxToggle"/);
assert.match(html,/pointerdown/);
assert.match(html,/pointermove/);
assert.match(html,/goalFor\(/);
assert.match(html,/AudioContext/);
for(const theme of ['neon','ice','lava','wave','gold','arcade'])assert.match(html,new RegExp("id:'"+theme+"'"));
const scripts=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(m=>m[1]);
assert.equal(scripts.length,1,'Must have one self-contained inline script');
new vm.Script(scripts[0],{filename:'puck-pulse-inline.js'});
assert.ok(!/<script[^>]+src=/.test(html),'No remote script dependencies');
console.log('PUCK PULSE static/JS/Worker checks passed');
