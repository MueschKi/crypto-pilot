import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html=readFileSync(new URL('../docs/eieralarm/index.html',import.meta.url),'utf8');
assert.match(html,/<title>EIERALARM LCD/);
assert.match(html,/@media \(orientation:portrait\)/);
for(const lane of ['tl','tr','bl','br']) assert.ok(html.includes('data-lane="'+lane+'"'),'Missing '+lane);
assert.match(html,/<g id="wolf"/);
assert.match(html,/<g id="eggs"/);
const a=html.indexOf('const LANES ='), b=html.indexOf('const game=new EggGame();');
assert.ok(a>0&&b>a,'Engine not found');
const sandbox={};
vm.runInNewContext(html.slice(a,b)+'\nthis.exports={LANES,MODE,EggGame}',sandbox);
const {LANES,MODE,EggGame}=sandbox.exports;
assert.equal(LANES.length,4);
const g=new EggGame(()=>0);
assert.equal(g.status,'ready');g.start(MODE.classic);
assert.equal(g.status,'running');g.selectLane('tl');
g.spawnEgg('tl',{travelMs:250});g.tick(250);
assert.equal(g.score,1,'Caught eggs score');
g.togglePause();assert.equal(g.status,'paused');
g.spawnEgg('tr',{travelMs:250});g.tick(250);
assert.equal(g.misses,0,'Pause freezes eggs');
g.togglePause();g.tick(250);assert.equal(g.misses,1);
g.spawnEgg('bl',{travelMs:250});g.tick(250);
g.spawnEgg('br',{travelMs:250});g.tick(250);
assert.equal(g.status,'over');assert.equal(g.misses,3);
const classic=new EggGame();classic.start(MODE.classic);
const turbo=new EggGame();turbo.start(MODE.turbo);
assert.ok(turbo.spawnDelay()<classic.spawnDelay());
assert.ok(turbo.travelTime()<classic.travelTime());
const score=g.score;g.tick(250);assert.equal(g.score,score);
console.log('PASS: four catch positions, landscape, score, pause, misses, game over and modes');
